#!/usr/bin/env bash
# Nightly copy of this node's irreplaceable local state to the manager, where
# the existing local snapshot and restic-to-B2 jobs already pick it up.
#
# Why this shape: the workers hold a little state that exists nowhere else
# (a game server's worlds, a compose file nobody committed). The node's two
# disks are a btrfs RAID1 pair; a pair is a mirror, not a backup, and a mirror
# copies deletions and corruption faithfully. This is the other half.
#
# Consistency without stopping anything: tar reads a read-only btrfs
# snapshot of /home, not the live tree, so a world being written mid-copy is
# captured as one coherent instant.
#
# Config from /etc/mediastack-node.conf:
#   BACKUP_PATHS   space-separated paths relative to /home (e.g. "user/crafty")
#   BACKUP_EXCLUDES  extra tar --exclude patterns, space-separated; wildcards
#                  are passed to tar as written (e.g. "user/app/*/cache")
#   BACKUP_DEST    user@manager. The key is locked on the manager to
#                  scripts/node-backup-receive.sh, which only ever writes
#                  <hostname>.tar under its own fixed directory.
#   BACKUP_SSH_KEY dedicated key for that, generated by the playbook
set -euo pipefail
CONF=/etc/mediastack-node.conf
BACKUP_PATHS=""; BACKUP_EXCLUDES=""; BACKUP_DEST=""; BACKUP_SSH_KEY=""
# shellcheck disable=SC1090
source "$CONF"
[ -n "$BACKUP_PATHS" ] && [ -n "$BACKUP_DEST" ] || { echo "nothing configured, skipping"; exit 0; }

TEXTFILE_DIR=/var/lib/docker/volumes/node_exporter_textfile/_data
snap=/.snapshots/backup-home
metric() {
  [ -d "$TEXTFILE_DIR" ] || return 0
  cat >"$TEXTFILE_DIR/.node_backup.prom.$$" <<M
# TYPE mediastack_node_backup_success gauge
mediastack_node_backup_success $1
# TYPE mediastack_node_backup_last_run_timestamp_seconds gauge
mediastack_node_backup_last_run_timestamp_seconds $(date +%s)
# TYPE mediastack_node_backup_bytes gauge
mediastack_node_backup_bytes ${2:-0}
M
  mv "$TEXTFILE_DIR/.node_backup.prom.$$" "$TEXTFILE_DIR/node_backup.prom"
}
cleanup() { btrfs subvolume delete "$snap" >/dev/null 2>&1 || true; }
trap 'cleanup; metric 0' ERR
trap cleanup EXIT

cleanup
btrfs subvolume snapshot -r /home "$snap" >/dev/null

args=()
# Patterns can hold wildcards ("crafty/servers/*/mods"); without noglob the
# shell would try to expand them against the current directory here instead
# of handing them to tar untouched.
set -f
for e in $BACKUP_EXCLUDES; do args+=(--exclude="$e"); done
set +f
ssh_opts=(-i "$BACKUP_SSH_KEY" -o BatchMode=yes -o UserKnownHostsFile="${BACKUP_KNOWN_HOSTS:-/etc/ssh/ssh_known_hosts}" -o StrictHostKeyChecking=yes)

# Uncompressed on purpose: restic on the manager dedupes an uncompressed tar
# well and a compressed one almost not at all. The receiver writes to a temp
# name and renames, so an interrupted run never replaces last night's good
# copy, and prints the byte count it stored.
# shellcheck disable=SC2086
size=$(tar -C "$snap" --warning=no-file-changed "${args[@]}" -cf - $BACKUP_PATHS \
  | ssh "${ssh_opts[@]}" "$BACKUP_DEST")
metric 1 "${size:-0}"
echo "node backup ok: ${size:-0} bytes"
